PHRASES = [
    (r"\bс тобой\b", "с вами"), (r"\bу тебя\b", "у вас"), (r"\bдля тебя\b", "для вас"),
    (r"\bТы готов\?", "Вы готовы?"), (r"\bЯ тебя понял\b", "Я вас понял"),
    (r"\bничего не понял\b", "ничего не поняли"),
]

_word_re = re.compile(r"[А-Яа-яЁё]+")


def _match_case(src: str, dst: str) -> str:
    if src.isupper() and len(src) > 1:
        return dst.upper()
    if src[0].isupper():
        return dst[0].upper() + dst[1:]
    return dst


def to_vy(text: str) -> str:
    # quoted titles («Ты способна на большее...») are not addressed to the reader
    parts = re.split(r"(«[^»]*»)", text)
    return "".join(p if p.startswith("«") else _convert(p) for p in parts)


def _convert(text: str) -> str:
    for pat, rep in PHRASES:
        text = re.sub(pat, lambda m: _match_case(m.group(0), rep), text, flags=re.IGNORECASE)

    def repl(m: re.Match) -> str:
        w = m.group(0)
        r = WORDS.get(w.lower())
        return _match_case(w, r) if r else w
    return _word_re.sub(repl, text)
